
function PathTestWithAlternates
    fig = figure('Name', 'Advanced Pathfinding System', ...
                 'Position', [100, 100, 900, 600]);

    % Axes where the map and paths are drawn
    hAxes = axes('Parent', fig, 'Units', 'pixels', ...
                 'Position', [250, 100, 600, 450]);

    % Grid size input
    uicontrol('Style', 'text', 'Position', [20, 540, 120, 20], ...
              'String', 'Grid Size:', ...
              'HorizontalAlignment', 'left');

    gridSizeEdit = uicontrol('Style', 'edit', ...
                            'Position', [150, 540, 80, 20], ...
                            'String', '16');

    % Obstacle density input
    uicontrol('Style', 'text', 'Position', [20, 500, 120, 20], ...
              'String', 'Obstacle Density (0-1):', ...
              'HorizontalAlignment', 'left');

    obstacleDensityEdit = uicontrol('Style', 'edit', ...
                                   'Position', [150, 500, 80, 20], ...
                                   'String', '0.2');

    % Generate Map button
    uicontrol('Style', 'pushbutton', ...
              'Position', [20, 460, 120, 30], ...
              'String', 'Generate Map', ...
              'Callback', @(s,e) generateMap( ...
                  gridSizeEdit, obstacleDensityEdit, hAxes));

    % Start point input
    uicontrol('Style', 'text', 'Position', [20, 420, 120, 20], ...
              'String', 'Start (x,y):', ...
              'HorizontalAlignment', 'left');

    startPointEdit = uicontrol('Style', 'edit', ...
                              'Position', [150, 420, 80, 20], ...
                              'String', '1,1');

    % End point input
    uicontrol('Style', 'text', 'Position', [20, 380, 120, 20], ...
              'String', 'End (x,y):', ...
              'HorizontalAlignment', 'left');

    endPointEdit = uicontrol('Style', 'edit', ...
                            'Position', [150, 380, 80, 20], ...
                            'String', '16,16');

    % Plot Start/End button
    uicontrol('Style', 'pushbutton', ...
              'Position', [20, 340, 120, 30], ...
              'String', 'Plot Start / End', ...
              'Callback', @(s,e) plotStartEnd( ...
                  startPointEdit, endPointEdit, hAxes));

    % Find Path button
    uicontrol('Style', 'pushbutton', ...
              'Position', [20, 300, 120, 30], ...
              'String', 'Find Path', ...
              'Callback', @(s,e) findPath( ...
                  startPointEdit, endPointEdit, hAxes));

    % Path selection dropdown
    uicontrol('Style', 'text', 'Position', [20, 260, 120, 20], ...
              'String', 'Select Path:', ...
              'HorizontalAlignment', 'left');

    pathDropdown = uicontrol('Style', 'popupmenu', ...
                             'Position', [150, 260, 60, 22], ...
                             'String', {'Select path'}, ...
                             'Callback', @(s,e) ...
                             highlightSelectedPath(hAxes));

    setappdata(hAxes, 'pathDropdown', pathDropdown);

    % Alternative path button
    uicontrol('Style', 'pushbutton', ...
              'Position', [20, 220, 150, 30], ...
              'String', 'Generate Alternative Path', ...
              'Callback', @(s,e) findAlternativePath( ...
                  startPointEdit, endPointEdit, hAxes));

    % Simulation button
    uicontrol('Style', 'pushbutton', ...
              'Position', [20, 180, 150, 30], ...
              'String', 'Start Simulation', ...
              'Callback', @(s,e) simulateDronePath( ...
                  startPointEdit, endPointEdit, hAxes));
end
